// Road network validation: connectivity, dead ends, overlapping/parallel segments, plots on roads, signals, bridges.
//   node scripts/validation/validate-roads.mjs        → prints a summary and writes docs/ROAD_VALIDATION.md
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
await build({ entryPoints: ['src/game/world/guzor/network.ts'], bundle: true, platform: 'node', format: 'esm', outfile: '/tmp/uzl-net.mjs', logLevel: 'silent', loader: { '.json': 'json' }, tsconfig: 'tsconfig.json' });
const { NET, OSM_ROADS, HAS_DEM } = await import('/tmp/uzl-net.mjs?' + Date.now());
const N = NET.nodes, E = NET.edges;
// connected components (by edges)
const comp = new Map(); let comps = 0, sizes = [];
for (const n of N) {
  if (!n.edges.length || comp.has(n.id)) continue;
  let size = 0; const stack = [n.id]; comp.set(n.id, comps);
  while (stack.length) { const u = stack.pop(); size++; for (const id of N[u].edges) { const e = E[id]; const v = e.a === u ? e.b : e.a; if (!comp.has(v)) { comp.set(v, comps); stack.push(v); } } }
  sizes.push(size); comps++;
}
sizes.sort((a, b) => b - a);
const deadEnds = N.filter((n) => n.edges.length === 1 && !E[n.edges[0]].alley && !E[n.edges[0]].major).length;
const alleyEnds = N.filter((n) => n.edges.length === 1 && E[n.edges[0]].alley).length;
const majorEnds = N.filter((n) => n.edges.length === 1 && E[n.edges[0]].major).length;
// parallel overlaps: sample points on each edge, find another edge (not sharing a node) closer than 3 m running parallel
let overlaps = 0;
for (const e of E) {
  let hits = 0, tot = 0;
  for (let s = 5; s < e.len - 5; s += 5) {
    const p = NET.pointAt(e, s); tot++;
    const r = NET.nearestRoad(p.x, p.z, 6, e.id);
    if (r && r.dist < 3 && r.e.a !== e.a && r.e.a !== e.b && r.e.b !== e.a && r.e.b !== e.b) {
      const q = NET.pointAt(r.e, r.s);
      if (Math.abs(p.tx * q.tx + p.tz * q.tz) > 0.9) hits++;
    }
  }
  if (tot && hits / tot > 0.5) overlaps++;
}
// plots overlapping a road surface
let lotsOnRoad = 0;
for (const L of NET.lots) {
  const c = Math.cos(L.rot), s = Math.sin(L.rot);
  const pts = [[0.5, 0.5], [L.w - 0.5, 0.5], [L.w - 0.5, L.d - 0.5], [0.5, L.d - 0.5], [L.w / 2, L.d / 2]].map(([a, b]) => ({ x: L.ox + a * c + b * s, z: L.oz - a * s + b * c }));
  if (pts.some((p) => NET.onRoad(p.x, p.z, 0))) lotsOnRoad++;
}
const res = {
  date: new Date().toISOString().slice(0, 10), source: OSM_ROADS ? 'OpenStreetMap (osm.json)' : 'traced from screenshots + generated local streets',
  elevation: HAS_DEM ? 'Copernicus DEM (dem.json)' : 'analytic (no DEM data)',
  nodes: N.filter((n) => n.edges.length).length, edges: E.length, km: +(E.reduce((a, e) => a + e.len, 0) / 1000).toFixed(1),
  components: comps, largestComponent: sizes[0], smallComponents: sizes.slice(1).reduce((a, b) => a + b, 0),
  deadEnds, alleyEnds, mapEdgeEnds: majorEnds, parallelOverlaps: overlaps, plotsOnRoad: lotsOnRoad, plots: NET.lots.length,
  signalJunctions: N.filter((n) => n.light).length, roundabouts: N.filter((n) => n.roundabout).length, bridgeEdges: E.filter((e) => e.bridge).length,
};
console.log(JSON.stringify(res, null, 1));
const md = `# ROAD_VALIDATION — ${res.date}\n\nGenerated by \`node scripts/validation/validate-roads.mjs\`.\n\n| Check | Result |\n|---|---|\n| Road geometry source | ${res.source} |\n| Elevation source | ${res.elevation} |\n| Junction nodes / road segments / length | ${res.nodes} / ${res.edges} / ${res.km} km |\n| Connected components | ${res.components} (largest: ${res.largestComponent} nodes; nodes outside it: ${res.smallComponents}) |\n| Unintended dead ends (generated streets) | ${res.deadEnds} |\n| Intentional dead-end lanes (berk ko‘cha) | ${res.alleyEnds} |\n| Road ends at the map edge | ${res.mapEdgeEnds} |\n| Parallel overlapping segments (< 3 m apart) | ${res.parallelOverlaps} |\n| Building plots touching a road surface | ${res.plotsOnRoad} of ${res.plots} |\n| Signalised junctions / roundabouts | ${res.signalJunctions} / ${res.roundabouts} |\n| Road segments with bridges | ${res.bridgeEdges} |\n`;
writeFileSync('docs/ROAD_VALIDATION.md', md);
